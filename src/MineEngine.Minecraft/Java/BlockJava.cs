using System.Globalization;
using MineEngine.Assets;
using MineEngine.Core.GameData;
using MineEngine.IR.Model;

namespace MineEngine.Minecraft.Java;

/// <summary>
/// Class of a block with advanced settings (package "block"): rotation (facing, face), water,
/// gravity, shape made of boxes, light opacity, connected sides, enchanting power, fire, redstone,
/// beacon beam and properties of the block state added by the user. The methods differ a little
/// between 1.20.1 and 1.21.1 (protected methods, codecs): they are written public, which both accept.
/// </summary>
public sealed partial class BlockJava
{
    private readonly IRBlock _block;
    private readonly JavaModNaming _naming;
    private readonly JavaGameApi _api;
    private readonly BlockOptions _options;
    private readonly string? _dropCondition;
    private readonly BlockEventCalls _events;
    private readonly SortedSet<string> _imports = new(StringComparer.Ordinal);

    /// <param name="dropCondition">Java call of the drop condition, with "level" and "position" (V0.7.11), or null.</param>
    /// <param name="events">Calls of the graphs that react to the events of the block (V0.7.11), or null.</param>
    public BlockJava(IRBlock block, JavaModNaming naming, JavaGameApi api, string? dropCondition = null, BlockEventCalls? events = null)
    {
        _block = block ?? throw new ArgumentNullException(nameof(block));
        _naming = naming ?? throw new ArgumentNullException(nameof(naming));
        _api = api ?? throw new ArgumentNullException(nameof(api));
        _options = block.Options;
        _dropCondition = dropCondition;
        _events = events ?? BlockEventCalls.None;
    }

    /// <summary>True when the block needs this class (otherwise it is a plain Block of the registry).</summary>
    public static bool IsNeeded(IRBlock block, IRContent content) =>
        block.Plant is not null || block.Options.NeedsOwnClass || block.DropCondition is not null || HasEvents(block, content);

    public static string Package(JavaModNaming naming) => naming.RootPackage + ".block";

    public static string ClassName(IRBlock block) => JavaNames.ToTypeName(block.Id.Value, "Custom") + "Block";

    private bool Modern => _api.UsesDataComponents;

    private bool HasFacing => _options.Rotation != BlockRotation.None;

    /// <summary>Java of the class.</summary>
    public JavaSourceWriter Write()
    {
        string className = ClassName(_block);
        if (_block.Plant is { } plant)
        {
            return WritePlant(plant, className);
        }

        Use("net.minecraft.world.level.block.Block", "net.minecraft.world.level.block.state.BlockBehaviour",
            "net.minecraft.world.level.block.state.BlockState", "net.minecraft.world.level.block.state.StateDefinition");
        (string baseClass, string superCall) = BaseClass();
        List<string> interfaces = [];
        if (_options.Waterloggable)
        {
            Use("net.minecraft.world.level.block.SimpleWaterloggedBlock");
            interfaces.Add("SimpleWaterloggedBlock");
        }

        if (_options.BeaconColor.Length > 0)
        {
            Use("net.minecraft.world.level.block.BeaconBeamBlock", "net.minecraft.world.item.DyeColor");
            interfaces.Add("BeaconBeamBlock");
        }

        var body = new JavaSourceWriter();
        body.Indent();
        WriteProperties(body);
        WriteShapes(body);
        body.OpenBlock($"public {className}(BlockBehaviour.Properties properties)")
            .Line(superCall);
        string defaults = DefaultState();
        if (defaults.Length > 0)
        {
            // A block base keeps the default state of its class of the game (half, hinge...).
            body.Line($"this.registerDefaultState({(_block.Settings.Model.IsBase() ? "this.defaultBlockState()" : "this.stateDefinition.any()")}{defaults});");
        }

        body.CloseBlock();
        WriteStateDefinition(body);
        WritePlacement(body);
        WriteWater(body);
        WriteOverrides(body, className);

        var w = new JavaSourceWriter();
        w.Line($"package {Package(_naming)};").Line();
        foreach (string import in _imports)
        {
            w.Line($"import {import};");
        }

        w.Line()
            .Line($"/** Block '{_block.Id}' with its advanced settings. Generated by Mine Engine. */")
            .Line($"public class {className} extends {baseClass}{(interfaces.Count > 0 ? " implements " + string.Join(", ", interfaces) : string.Empty)} {{");
        foreach (string line in body.ToString().TrimEnd().Split('\n'))
        {
            w.Line(line.TrimEnd('\r'));
        }

        w.Line("}");
        return w;
    }

    private void Use(params string[] imports) => _imports.UnionWith(imports);

    /// <summary>Parent class and call of its constructor.</summary>
    private (string Base, string SuperCall) BaseClass()
    {
        if (_block.Settings.Model.IsBase())
        {
            // A block base (V0.7.11) with advanced settings: its class of the game, then the overrides.
            Use([.. BlockBaseJava.Imports(_block.Settings.Model)]);
            (string before, string after) = BlockBaseJava.Arguments(_block.Settings.Model, _block.Settings.Sound, Modern);
            return (BlockBaseJava.ClassName(_block.Settings.Model), $"super({before}properties{after});");
        }

        if (_options.HasGravity)
        {
            Use("net.minecraft.world.level.block.FallingBlock");
            return ("FallingBlock", "super(properties);");
        }

        if (_block.Settings.Model == BlockModelKind.Column)
        {
            Use("net.minecraft.world.level.block.RotatedPillarBlock");
            return ("RotatedPillarBlock", "super(properties);");
        }

        if (_block.Settings.DropsExperience)
        {
            Use("net.minecraft.world.level.block.DropExperienceBlock", "net.minecraft.util.valueproviders.UniformInt");
            (string head, string tail) = _api.ExperienceBlockConstruction(_block.Settings.ExperienceMin, _block.Settings.ExperienceMax);
            return ("DropExperienceBlock", head.Replace("new DropExperienceBlock(", "super(", StringComparison.Ordinal) + "properties" + tail + ";");
        }

        return ("Block", "super(properties);");
    }

    // ----- Plants (V0.7.0) -----

    /// <summary>
    /// Class of a plant: a bush (flower, growing plant), a double plant or a crop, with the soil it
    /// can be placed on, the growth of a growing plant, and the seeds of a crop.
    /// </summary>
    private JavaSourceWriter WritePlant(IRPlant plant, string className)
    {
        Use("net.minecraft.world.level.block.Block", "net.minecraft.world.level.block.state.BlockBehaviour",
            "net.minecraft.world.level.block.state.BlockState", "net.minecraft.world.level.BlockGetter", "net.minecraft.core.BlockPos");
        string baseClass = plant.Kind switch
        {
            PlantKind.Tall => "DoublePlantBlock",
            PlantKind.Crop => "CropBlock",
            _ => "BushBlock",
        };
        Use("net.minecraft.world.level.block." + baseClass);
        var body = new JavaSourceWriter();
        body.Indent();
        if (plant.Kind == PlantKind.Growing)
        {
            Use("net.minecraft.world.level.block.state.properties.BlockStateProperties", "net.minecraft.world.level.block.state.properties.IntegerProperty",
                "net.minecraft.world.level.block.state.StateDefinition", "net.minecraft.server.level.ServerLevel", "net.minecraft.util.RandomSource");
            body.Line("public static final IntegerProperty AGE = BlockStateProperties.AGE_15;")
                .Line($"public static final int MAX_HEIGHT = {Math.Max(1, plant.MaxHeight)};")
                .Line();
        }

        body.OpenBlock($"public {className}(BlockBehaviour.Properties properties)")
            .Line("super(properties);");
        if (plant.Kind == PlantKind.Growing)
        {
            body.Line("this.registerDefaultState(this.stateDefinition.any().setValue(AGE, 0));");
        }

        body.CloseBlock();
        if (plant.Kind != PlantKind.Crop)
        {
            body.Line()
                .Line("@Override")
                .OpenBlock("protected boolean mayPlaceOn(BlockState state, BlockGetter level, BlockPos position)")
                .Line($"return {(plant.Kind == PlantKind.Growing ? "state.is(this) || " : string.Empty)}{Soil(plant.Soil)};")
                .CloseBlock();
        }

        if (plant.Kind == PlantKind.Growing)
        {
            body.Line()
                .Line("@Override")
                .OpenBlock("protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder)")
                .Line("super.createBlockStateDefinition(builder);")
                .Line("builder.add(AGE);")
                .CloseBlock()
                .Line()
                .Line("/** Grows by one block when its age reaches 15, up to MAX_HEIGHT blocks, like sugar cane. */")
                .Line("@Override")
                .OpenBlock("public void randomTick(BlockState state, ServerLevel level, BlockPos position, RandomSource random)")
                .OpenBlock("if (!level.isEmptyBlock(position.above()))")
                .Line("return;")
                .CloseBlock()
                .Line("int height = 1;")
                .OpenBlock("while (level.getBlockState(position.below(height)).is(this))")
                .Line("height++;")
                .CloseBlock()
                .OpenBlock("if (height >= MAX_HEIGHT)")
                .Line("return;")
                .CloseBlock()
                .Line("int age = state.getValue(AGE);")
                .OpenBlock("if (age == 15)")
                .Line("level.setBlockAndUpdate(position.above(), this.defaultBlockState());")
                .Line("level.setBlock(position, state.setValue(AGE, 0), 4);")
                .CloseBlock()
                .OpenBlock("else")
                .Line("level.setBlock(position, state.setValue(AGE, age + 1), 4);")
                .CloseBlock()
                .CloseBlock();
        }

        if (plant.Kind == PlantKind.Crop)
        {
            Use("net.minecraft.world.level.ItemLike", $"{_naming.RegistryPackage}.{_naming.ItemsClass}");
            body.Line()
                .Line("/** The item of the crop is its seeds. */")
                .Line("@Override")
                .OpenBlock("protected ItemLike getBaseSeedId()")
                .Line($"return {_naming.ItemsClass}.{_naming.ConstantFor(_block.Id)}.get();")
                .CloseBlock();
        }

        if (Modern)
        {
            // Since 1.20.5 a block of these kinds gives its codec.
            Use("com.mojang.serialization.MapCodec");
            body.Line()
                .Line("@Override")
                .OpenBlock($"public MapCodec<? extends {baseClass}> codec()")
                .Line($"return simpleCodec({className}::new);")
                .CloseBlock();
        }

        var w = new JavaSourceWriter();
        w.Line($"package {Package(_naming)};").Line();
        foreach (string import in _imports)
        {
            w.Line($"import {import};");
        }

        w.Line()
            .Line($"/** Plant '{_block.Id}'. Generated by Mine Engine. */")
            .Line($"public class {className} extends {baseClass} {{");
        foreach (string line in body.ToString().TrimEnd().Split('\n'))
        {
            w.Line(line.TrimEnd('\r'));
        }

        w.Line("}");
        return w;
    }

    /// <summary>Java test of the block under the plant.</summary>
    private string Soil(PlantSoil soil)
    {
        switch (soil)
        {
            case PlantSoil.Sand:
                Use("net.minecraft.tags.BlockTags");
                return "state.is(BlockTags.SAND)";
            case PlantSoil.Farmland:
                Use("net.minecraft.world.level.block.Blocks");
                return "state.is(Blocks.FARMLAND)";
            case PlantSoil.AnySolid:
                Use("net.minecraft.core.Direction");
                return "state.isFaceSturdy(level, position, Direction.UP)";
            default:
                Use("net.minecraft.tags.BlockTags", "net.minecraft.world.level.block.Blocks");
                return "state.is(BlockTags.DIRT) || state.is(Blocks.FARMLAND)";
        }
    }

    // ----- Properties of the block state -----

    private void WriteProperties(JavaSourceWriter w)
    {
        if (HasFacing)
        {
            Use("net.minecraft.world.level.block.state.properties.BlockStateProperties", "net.minecraft.world.level.block.state.properties.DirectionProperty",
                "net.minecraft.core.Direction");
            w.Line($"public static final DirectionProperty FACING = BlockStateProperties.{(_options.Rotation == BlockRotation.Horizontal ? "HORIZONTAL_FACING" : "FACING")};");
        }

        if (_options.HasPitchRotation)
        {
            Use("net.minecraft.world.level.block.state.properties.EnumProperty", "net.minecraft.world.level.block.state.properties.AttachFace");
            w.Line("public static final EnumProperty<AttachFace> FACE = BlockStateProperties.ATTACH_FACE;");
        }

        if (_options.Waterloggable)
        {
            Use("net.minecraft.world.level.block.state.properties.BlockStateProperties", "net.minecraft.world.level.block.state.properties.BooleanProperty");
            w.Line("public static final BooleanProperty WATERLOGGED = BlockStateProperties.WATERLOGGED;");
        }

        if (TracksRedstone)
        {
            // Remembers the signal, so that the redstone on and off events run once per change.
            Use("net.minecraft.world.level.block.state.properties.BooleanProperty");
            w.Line("public static final BooleanProperty REDSTONE_POWERED = BooleanProperty.create(\"redstone_powered\");");
        }

        foreach (BlockCustomProperty property in _options.Properties)
        {
            string constant = PropertyConstant(property);
            switch (property.Kind)
            {
                case BlockPropertyKind.Boolean:
                    Use("net.minecraft.world.level.block.state.properties.BooleanProperty");
                    w.Line($"public static final BooleanProperty {constant} = BooleanProperty.create({JavaNames.StringLiteral(property.Name)});");
                    break;
                case BlockPropertyKind.Integer:
                    Use("net.minecraft.world.level.block.state.properties.IntegerProperty");
                    w.Line($"public static final IntegerProperty {constant} = IntegerProperty.create({JavaNames.StringLiteral(property.Name)}, {property.Min}, {property.Max});");
                    break;
                default:
                    Use("net.minecraft.world.level.block.state.properties.EnumProperty", "net.minecraft.util.StringRepresentable");
                    string type = ChoiceType(property);
                    w.Line($"public enum {type} implements StringRepresentable {{")
                        .Line("    " + string.Join(", ", property.Values.Select(v => $"{v.ToUpperInvariant()}({JavaNames.StringLiteral(v)})")) + ";")
                        .Line()
                        .Line("    private final String name;")
                        .Line()
                        .Line($"    {type}(String name) {{")
                        .Line("        this.name = name;")
                        .Line("    }")
                        .Line()
                        .Line("    @Override")
                        .Line("    public String getSerializedName() {")
                        .Line("        return this.name;")
                        .Line("    }")
                        .Line("}")
                        .Line()
                        .Line($"public static final EnumProperty<{type}> {constant} = EnumProperty.create({JavaNames.StringLiteral(property.Name)}, {type}.class);");
                    break;
            }
        }

        w.Line();
    }

    private static string PropertyConstant(BlockCustomProperty property) => "PROPERTY_" + property.Name.ToUpperInvariant();

    private static string ChoiceType(BlockCustomProperty property) => JavaNames.ToTypeName(property.Name, "Choice") + "Value";

    private string DefaultState()
    {
        var parts = new List<string>();
        if (HasFacing)
        {
            parts.Add(".setValue(FACING, Direction.NORTH)");
        }

        if (_options.HasPitchRotation)
        {
            parts.Add(".setValue(FACE, AttachFace.WALL)");
        }

        if (_options.Waterloggable)
        {
            parts.Add(".setValue(WATERLOGGED, false)");
        }

        if (TracksRedstone)
        {
            parts.Add(".setValue(REDSTONE_POWERED, false)");
        }

        foreach (BlockCustomProperty property in _options.Properties)
        {
            string value = property.Kind switch
            {
                BlockPropertyKind.Boolean => "false",
                BlockPropertyKind.Integer => property.Min.ToString(CultureInfo.InvariantCulture),
                _ => $"{ChoiceType(property)}.{property.Values[0].ToUpperInvariant()}",
            };
            parts.Add($".setValue({PropertyConstant(property)}, {value})");
        }

        return string.Concat(parts);
    }

    private void WriteStateDefinition(JavaSourceWriter w)
    {
        var added = new List<string>();
        if (HasFacing)
        {
            added.Add("FACING");
        }

        if (_options.HasPitchRotation)
        {
            added.Add("FACE");
        }

        if (_options.Waterloggable)
        {
            added.Add("WATERLOGGED");
        }

        if (TracksRedstone)
        {
            added.Add("REDSTONE_POWERED");
        }

        added.AddRange(_options.Properties.Select(PropertyConstant));
        if (_block.Appearances.Count > 0)
        {
            Use($"{_naming.RegistryPackage}.{_naming.BlocksClass}");
            added.Add($"{_naming.BlocksClass}.{_naming.ConstantFor(_block.Id)}_APPEARANCE");
        }

        if (added.Count == 0)
        {
            return;
        }

        w.Line()
            .Line("@Override")
            .OpenBlock("protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder)")
            .Line("super.createBlockStateDefinition(builder);")
            .Line($"builder.add({string.Join(", ", added)});")
            .CloseBlock();
    }

    private void WritePlacement(JavaSourceWriter w)
    {
        if (!HasFacing && !_options.Waterloggable)
        {
            return;
        }

        Use("net.minecraft.world.item.context.BlockPlaceContext");
        w.Line()
            .Line("@Override")
            .OpenBlock("public BlockState getStateForPlacement(BlockPlaceContext context)")
            .Line("BlockState state = this.defaultBlockState();");
        if (_options.HasPitchRotation)
        {
            w.Line("Direction looked = context.getNearestLookingDirection();")
                .OpenBlock("if (looked.getAxis() == Direction.Axis.Y)")
                .Line("state = state.setValue(FACE, looked == Direction.UP ? AttachFace.CEILING : AttachFace.FLOOR).setValue(FACING, context.getHorizontalDirection());")
                .CloseBlock()
                .OpenBlock("else")
                .Line("state = state.setValue(FACE, AttachFace.WALL).setValue(FACING, looked.getOpposite());")
                .CloseBlock();
        }
        else if (_options.Rotation == BlockRotation.Horizontal)
        {
            w.Line("state = state.setValue(FACING, context.getHorizontalDirection().getOpposite());");
        }
        else if (_options.Rotation == BlockRotation.AllDirections)
        {
            w.Line("state = state.setValue(FACING, context.getNearestLookingDirection().getOpposite());");
        }

        if (_options.Waterloggable)
        {
            Use("net.minecraft.world.level.material.Fluids");
            w.Line("state = state.setValue(WATERLOGGED, context.getLevel().getFluidState(context.getClickedPos()).getType() == Fluids.WATER);");
        }

        w.Line("return state;")
            .CloseBlock();

        if (HasFacing)
        {
            Use("net.minecraft.world.level.block.Rotation", "net.minecraft.world.level.block.Mirror");
            w.Line()
                .Line("@Override")
                .OpenBlock("public BlockState rotate(BlockState state, Rotation rotation)")
                .Line("return state.setValue(FACING, rotation.rotate(state.getValue(FACING)));")
                .CloseBlock()
                .Line()
                .Line("@Override")
                .OpenBlock("public BlockState mirror(BlockState state, Mirror mirror)")
                .Line("return state.rotate(mirror.getRotation(state.getValue(FACING)));")
                .CloseBlock();
        }
    }

    private void WriteWater(JavaSourceWriter w)
    {
        if (!_options.Waterloggable)
        {
            return;
        }

        Use("net.minecraft.world.level.material.FluidState", "net.minecraft.world.level.material.Fluids", "net.minecraft.world.level.LevelAccessor",
            "net.minecraft.core.BlockPos", "net.minecraft.core.Direction");
        w.Line()
            .Line("@Override")
            .OpenBlock("public FluidState getFluidState(BlockState state)")
            .Line("return state.getValue(WATERLOGGED) ? Fluids.WATER.getSource(false) : super.getFluidState(state);")
            .CloseBlock()
            .Line()
            .Line("@Override")
            .OpenBlock("public BlockState updateShape(BlockState state, Direction direction, BlockState neighbor, LevelAccessor level, BlockPos position, BlockPos neighborPosition)")
            .OpenBlock("if (state.getValue(WATERLOGGED))")
            .Line("level.scheduleTick(position, Fluids.WATER, Fluids.WATER.getTickDelay(level));")
            .CloseBlock()
            .Line("return super.updateShape(state, direction, neighbor, level, position, neighborPosition);")
            .CloseBlock();
    }

    // ----- Shape -----

    /// <summary>Shapes of the block (one per facing when it turns), from boxes in pixels.</summary>
    private void WriteShapes(JavaSourceWriter w)
    {
        if (_options.Boxes.Count == 0)
        {
            return;
        }

        Use("net.minecraft.world.phys.shapes.VoxelShape", "net.minecraft.world.phys.shapes.Shapes", "net.minecraft.world.phys.shapes.BooleanOp");
        if (!HasFacing)
        {
            w.Line($"private static final VoxelShape SHAPE = {Shape(_options.Boxes)};").Line();
            return;
        }

        foreach (string direction in Directions())
        {
            w.Line($"private static final VoxelShape SHAPE_{direction.ToUpperInvariant()} = {Shape([.. _options.Boxes.Select(b => Turn(b, direction))])};");
        }

        w.Line();
    }

    private IEnumerable<string> Directions() => _options.Rotation == BlockRotation.AllDirections
        ? ["north", "east", "south", "west", "up", "down"]
        : ["north", "east", "south", "west"];

    /// <summary>"Shapes.or(Block.box(...), ...)" minus the subtracted boxes.</summary>
    private static string Shape(IReadOnlyList<BlockBox> boxes)
    {
        List<BlockBox> added = [.. boxes.Where(b => !b.Subtract)];
        string shape = added.Count switch
        {
            0 => "Shapes.block()",
            1 => Box(added[0]),
            _ => $"Shapes.or({Box(added[0])}, {string.Join(", ", added.Skip(1).Select(Box))})",
        };
        foreach (BlockBox hole in boxes.Where(b => b.Subtract))
        {
            shape = $"Shapes.join({shape}, {Box(hole)}, BooleanOp.ONLY_FIRST)";
        }

        return shape;
    }

    private static string Box(BlockBox b) => string.Create(CultureInfo.InvariantCulture,
        $"Block.box({Number(b.MinX)}, {Number(b.MinY)}, {Number(b.MinZ)}, {Number(b.MaxX)}, {Number(b.MaxY)}, {Number(b.MaxZ)})");

    private static string Number(double value) => Math.Round(value, 3).ToString("0.0##", CultureInfo.InvariantCulture);

    /// <summary>A box drawn for a block facing north, turned toward <paramref name="direction"/>.</summary>
    public static BlockBox Turn(BlockBox box, string direction)
    {
        (double X, double Y, double Z) Point(double x, double y, double z) => direction switch
        {
            "east" => (16 - z, y, x),
            "south" => (16 - x, y, 16 - z),
            "west" => (z, y, 16 - x),
            "up" => (x, 16 - z, y),
            "down" => (x, z, 16 - y),
            _ => (x, y, z),
        };

        var a = Point(box.MinX, box.MinY, box.MinZ);
        var b = Point(box.MaxX, box.MaxY, box.MaxZ);
        return box with
        {
            MinX = Math.Min(a.X, b.X), MaxX = Math.Max(a.X, b.X),
            MinY = Math.Min(a.Y, b.Y), MaxY = Math.Max(a.Y, b.Y),
            MinZ = Math.Min(a.Z, b.Z), MaxZ = Math.Max(a.Z, b.Z),
        };
    }

    // ----- Other behaviors -----

    private void WriteOverrides(JavaSourceWriter w, string className)
    {
        WriteEvents(w);

        if (_dropCondition is not null)
        {
            // The loot table gives the drops; the function of the project can take them away.
            Use("java.util.List", "net.minecraft.core.BlockPos", "net.minecraft.server.level.ServerLevel", "net.minecraft.world.item.ItemStack",
                "net.minecraft.world.level.storage.loot.LootParams", "net.minecraft.world.level.storage.loot.parameters.LootContextParams");
            w.Line()
                .Line("@Override")
                .OpenBlock("public List<ItemStack> getDrops(BlockState state, LootParams.Builder builder)")
                .Line("ServerLevel level = builder.getLevel();")
                .Line("BlockPos position = BlockPos.containing(builder.getParameter(LootContextParams.ORIGIN));")
                .Line($"return {_dropCondition} ? super.getDrops(state, builder) : List.of();")
                .CloseBlock();
        }

        if (_options.Boxes.Count > 0)
        {
            Use("net.minecraft.world.level.BlockGetter", "net.minecraft.core.BlockPos", "net.minecraft.world.phys.shapes.CollisionContext");
            string shape = HasFacing
                ? "switch (state.getValue(FACING)) { " + string.Join(" ", Directions().Select(d => $"case {d.ToUpperInvariant()} -> SHAPE_{d.ToUpperInvariant()};"))
                  + (_options.Rotation == BlockRotation.Horizontal ? " default -> SHAPE_NORTH;" : string.Empty) + " }"
                : "SHAPE";
            w.Line()
                .Line("@Override")
                .OpenBlock("public VoxelShape getShape(BlockState state, BlockGetter level, BlockPos position, CollisionContext context)")
                .Line($"return {shape};")
                .CloseBlock();
        }

        if (_options.CustomLightOpacity)
        {
            Use("net.minecraft.world.level.BlockGetter", "net.minecraft.core.BlockPos");
            w.Line()
                .Line("@Override")
                .OpenBlock("public int getLightBlock(BlockState state, BlockGetter level, BlockPos position)")
                .Line($"return {Math.Clamp(_options.LightOpacity, 0, 15)};")
                .CloseBlock();
        }

        if (_options.ConnectedSides)
        {
            Use("net.minecraft.core.Direction");
            w.Line()
                .Line("/** Like glass: the faces between two blocks of this type are not drawn. */")
                .Line("@Override")
                .OpenBlock("public boolean skipRendering(BlockState state, BlockState neighbor, Direction direction)")
                .Line("return neighbor.is(this) || super.skipRendering(state, neighbor, direction);")
                .CloseBlock();
        }

        if (_options.EnchantPowerBonus > 0)
        {
            Use("net.minecraft.world.level.LevelReader", "net.minecraft.core.BlockPos");
            w.Line()
                .Line("@Override")
                .OpenBlock("public float getEnchantPowerBonus(BlockState state, LevelReader level, BlockPos position)")
                .Line($"return {JavaNames.FloatLiteral(_options.EnchantPowerBonus)};")
                .CloseBlock();
        }

        if (_options.Flammability > 0 || _options.FireSpreadSpeed > 0)
        {
            Use("net.minecraft.world.level.BlockGetter", "net.minecraft.core.BlockPos", "net.minecraft.core.Direction");
            w.Line()
                .Line("@Override")
                .OpenBlock("public int getFlammability(BlockState state, BlockGetter level, BlockPos position, Direction direction)")
                .Line($"return {Math.Max(0, _options.Flammability)};")
                .CloseBlock()
                .Line()
                .Line("@Override")
                .OpenBlock("public int getFireSpreadSpeed(BlockState state, BlockGetter level, BlockPos position, Direction direction)")
                .Line($"return {Math.Max(0, _options.FireSpreadSpeed)};")
                .CloseBlock();
        }

        if (_options.EmitsRedstone)
        {
            Use("net.minecraft.world.level.BlockGetter", "net.minecraft.core.BlockPos", "net.minecraft.core.Direction");
            w.Line()
                .Line("@Override")
                .OpenBlock("public boolean isSignalSource(BlockState state)")
                .Line("return true;")
                .CloseBlock()
                .Line()
                .Line("@Override")
                .OpenBlock("public int getSignal(BlockState state, BlockGetter level, BlockPos position, Direction direction)")
                .Line($"return {_options.RedstonePower};")
                .CloseBlock();
        }

        if (_options.RedstoneConnects || _options.EmitsRedstone)
        {
            Use("net.minecraft.world.level.BlockGetter", "net.minecraft.core.BlockPos", "net.minecraft.core.Direction");
            w.Line()
                .Line("@Override")
                .OpenBlock("public boolean canConnectRedstone(BlockState state, BlockGetter level, BlockPos position, Direction direction)")
                .Line("return true;")
                .CloseBlock();
        }

        if (_options.BeaconColor.Length > 0)
        {
            w.Line()
                .Line("@Override")
                .OpenBlock("public DyeColor getColor()")
                .Line($"return DyeColor.{_options.BeaconColor};")
                .CloseBlock();
        }

        if (_options.HasGravity && Modern)
        {
            // Since 1.20.5 a falling block gives its codec.
            Use("com.mojang.serialization.MapCodec");
            w.Line()
                .Line("@Override")
                .OpenBlock("protected MapCodec<? extends FallingBlock> codec()")
                .Line($"return simpleCodec({className}::new);")
                .CloseBlock();
        }
    }
