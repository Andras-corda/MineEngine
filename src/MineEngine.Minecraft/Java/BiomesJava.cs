using System.Globalization;
using MineEngine.IR.Model;

namespace MineEngine.Minecraft.Java;

/// <summary>
/// Class ModBiomes of the package "world" (V0.7.0): when the server is about to start, the biomes of
/// the mod are added to the biome source of the overworld at the climate chosen for them, the
/// features of the chunk generator are sorted again, and their surface blocks are put in front of
/// the surface rules. The fields of the game are found by their type, so the same code works with
/// the names of 1.20.1 (obfuscated in the game) and of 1.21.1.
/// </summary>
public sealed class BiomesJava
{
    public const string ClassName = "ModBiomes";

    private readonly JavaModNaming _naming;
    private readonly JavaGameApi _api;
    private readonly string _modId;

    public BiomesJava(JavaModNaming naming, JavaGameApi api, string modId)
    {
        _naming = naming ?? throw new ArgumentNullException(nameof(naming));
        _api = api ?? throw new ArgumentNullException(nameof(api));
        _modId = modId;
    }

    public static string Package(JavaModNaming naming) => naming.RootPackage + ".world";

    /// <summary>Java of the class; <paramref name="aboutToStart"/> is the event class of the loader.</summary>
    public JavaSourceWriter Write(IReadOnlyList<IRBiome> biomes, (string Expression, string Import) gameBus, string aboutToStart)
    {
        string eventName = aboutToStart[(aboutToStart.LastIndexOf('.') + 1)..];
        var w = new JavaSourceWriter();
        w.Line($"package {Package(_naming)};").Line();
        foreach (string import in new SortedSet<string>(StringComparer.Ordinal)
                 {
                     aboutToStart, gameBus.Import, "com.google.common.base.Suppliers", "com.mojang.datafixers.util.Pair",
                     "java.lang.reflect.Field", "java.lang.reflect.Method", "java.util.ArrayList", "java.util.List", "java.util.function.Supplier",
                     "net.minecraft.core.Holder", "net.minecraft.core.Registry", "net.minecraft.core.registries.BuiltInRegistries",
                     "net.minecraft.core.registries.Registries", "net.minecraft.resources.ResourceKey", "net.minecraft.resources.ResourceLocation",
                     "net.minecraft.server.MinecraftServer", "net.minecraft.world.level.biome.Biome", "net.minecraft.world.level.biome.BiomeSource",
                     "net.minecraft.world.level.biome.Climate", "net.minecraft.world.level.biome.FeatureSorter",
                     "net.minecraft.world.level.biome.MultiNoiseBiomeSource", "net.minecraft.world.level.block.state.BlockState",
                     "net.minecraft.world.level.chunk.ChunkGenerator", "net.minecraft.world.level.dimension.LevelStem",
                     "net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator", "net.minecraft.world.level.levelgen.NoiseGeneratorSettings",
                     "net.minecraft.world.level.levelgen.SurfaceRules",
                 })
        {
            w.Line($"import {import};");
        }

        List<IRBiome> injected = [.. biomes.Where(b => b.GeneratesInOverworld)];
        w.Line()
            .Line("/** Biomes of the mod added to the overworld. Generated by Mine Engine. */")
            .OpenBlock($"public final class {ClassName}")
            .OpenBlock("public static void register()")
            .Line($"{gameBus.Expression}.addListener({ClassName}::onServerAboutToStart);")
            .CloseBlock()
            .Line()
            .OpenBlock($"private static void onServerAboutToStart({eventName} event)")
            .Line("MinecraftServer server = event.getServer();")
            .Line("Registry<Biome> biomes = server.registryAccess().registryOrThrow(Registries.BIOME);")
            .Line("LevelStem overworld = server.registryAccess().registryOrThrow(Registries.LEVEL_STEM).get(LevelStem.OVERWORLD);")
            .OpenBlock("if (overworld == null || !(overworld.generator().getBiomeSource() instanceof MultiNoiseBiomeSource source))")
            .Line("return;")
            .CloseBlock()
            .Line("ChunkGenerator generator = overworld.generator();")
            .OpenBlock("try")
            .Line("List<Pair<Climate.ParameterPoint, Holder<Biome>>> points = new ArrayList<>(parameters(source).values());")
            .Line("int before = points.size();");
        foreach (IRBiome biome in injected)
        {
            w.Line($"add(points, biomes, {JavaNames.StringLiteral($"{_modId}:{biome.Id}")}, Climate.parameters({Span(biome.ClimateTemperature)}, {Span(biome.Humidity)}, "
                   + $"{Span(biome.Continentalness)}, {Span(biome.Erosion)}, Climate.Parameter.point(0.0f), {Span(biome.Weirdness)}, 0.0f));");
        }

        w.OpenBlock("if (points.size() == before)")
            .Line("return;")
            .CloseBlock()
            .Line("MultiNoiseBiomeSource injected = MultiNoiseBiomeSource.createFromList(new Climate.ParameterList<>(points));")
            .Line("set(ChunkGenerator.class, generator, BiomeSource.class, injected);")
            .Line("Supplier<?> features = Suppliers.memoize(() -> FeatureSorter.buildFeaturesPerStep(List.copyOf(injected.possibleBiomes()),")
            .Line("    biome -> biome.value().getGenerationSettings().features(), true));")
            .Line("set(ChunkGenerator.class, generator, Supplier.class, features);");

        List<IRBiome> surfaces = [.. injected.Where(b => b.TopBlock is not null || b.UnderBlock is not null)];
        if (surfaces.Count > 0)
        {
            w.OpenBlock("if (generator instanceof NoiseBasedChunkGenerator noise)")
                .Line("NoiseGeneratorSettings settings = noise.generatorSettings().value();")
                .Line("SurfaceRules.RuleSource rules = SurfaceRules.sequence(");
            for (int i = 0; i < surfaces.Count; i++)
            {
                w.Line("    " + SurfaceRule(surfaces[i]) + (i == surfaces.Count - 1 ? "," : ","));
            }

            w.Line("    settings.surfaceRule());")
                .Line("NoiseGeneratorSettings changed = new NoiseGeneratorSettings(settings.noiseSettings(), settings.defaultBlock(), settings.defaultFluid(),")
                .Line("    settings.noiseRouter(), rules, settings.spawnTarget(), settings.seaLevel(), settings.disableMobGeneration(), settings.aquifersEnabled(),")
                .Line("    settings.oreVeinsEnabled(), settings.useLegacyRandomSource());")
                .Line("set(NoiseBasedChunkGenerator.class, noise, Holder.class, Holder.direct(changed));")
                .CloseBlock();
        }

        w.CloseBlock()
            .OpenBlock("catch (ReflectiveOperationException | RuntimeException exception)")
            .Line("// The overworld keeps its biomes: the biomes of the mod stay usable by /locate and /fillbiome.")
            .Line("System.err.println(\"[Mine Engine] The biomes could not be added to the overworld: \" + exception);")
            .CloseBlock()
            .CloseBlock()
            .Line()
            .OpenBlock("private static void add(List<Pair<Climate.ParameterPoint, Holder<Biome>>> points, Registry<Biome> biomes, String id, Climate.ParameterPoint point)")
            .Line($"ResourceKey<Biome> key = ResourceKey.create(Registries.BIOME, {_api.ParseResourceLocation("id")});")
            .OpenBlock("if (biomes.getHolder(key).isPresent() && points.stream().noneMatch(pair -> pair.getSecond().is(key)))")
            .Line("points.add(Pair.of(point, biomes.getHolderOrThrow(key)));")
            .CloseBlock()
            .CloseBlock()
            .Line()
            .Line("/** Climate.ParameterList of the source (a private method of the game, found by its return type). */")
            .Line("@SuppressWarnings(\"unchecked\")")
            .OpenBlock("private static Climate.ParameterList<Holder<Biome>> parameters(MultiNoiseBiomeSource source) throws ReflectiveOperationException")
            .OpenBlock("for (Method method : MultiNoiseBiomeSource.class.getDeclaredMethods())")
            .OpenBlock("if (method.getParameterCount() == 0 && method.getReturnType() == Climate.ParameterList.class)")
            .Line("method.setAccessible(true);")
            .Line("return (Climate.ParameterList<Holder<Biome>>) method.invoke(source);")
            .CloseBlock()
            .CloseBlock()
            .Line("throw new NoSuchMethodException(\"parameters\");")
            .CloseBlock()
            .Line()
            .Line("/** Changes the field of the given type of the object (the only one of that type in its class). */")
            .OpenBlock("private static void set(Class<?> owner, Object target, Class<?> type, Object value) throws ReflectiveOperationException")
            .OpenBlock("for (Field field : owner.getDeclaredFields())")
            .OpenBlock("if (field.getType() == type && !java.lang.reflect.Modifier.isStatic(field.getModifiers()))")
            .Line("field.setAccessible(true);")
            .Line("field.set(target, value);")
            .Line("return;")
            .CloseBlock()
            .CloseBlock()
            .Line("throw new NoSuchFieldException(type.getSimpleName());")
            .CloseBlock()
            .Line()
            .OpenBlock("private static BlockState block(String id)")
            .Line($"return BuiltInRegistries.BLOCK.get({_api.ParseResourceLocation("id")}).defaultBlockState();")
            .CloseBlock()
            .Line()
            .OpenBlock($"private {ClassName}()")
            .CloseBlock()
            .CloseBlock();
        return w;
    }

    private static string Span(MineEngine.Assets.ClimateRange range) => string.Create(CultureInfo.InvariantCulture,
        $"Climate.Parameter.span({range.Min:0.0###}f, {range.Max:0.0###}f)");

    /// <summary>Surface of the biome: its top block on the floor (out of water), its under block below.</summary>
    private string SurfaceRule(IRBiome biome)
    {
        string key = $"ResourceKey.create(Registries.BIOME, {_api.ParseResourceLocation(JavaNames.StringLiteral($"{_modId}:{biome.Id}"))})";
        var parts = new List<string>();
        if (biome.TopBlock is { } top)
        {
            parts.Add($"SurfaceRules.ifTrue(SurfaceRules.ON_FLOOR, SurfaceRules.ifTrue(SurfaceRules.waterBlockCheck(-1, 0), SurfaceRules.state(block({JavaNames.StringLiteral(top)}))))");
        }

        if (biome.UnderBlock is { } under)
        {
            parts.Add($"SurfaceRules.ifTrue(SurfaceRules.UNDER_FLOOR, SurfaceRules.state(block({JavaNames.StringLiteral(under)})))");
        }

        string inner = parts.Count == 1 ? parts[0] : $"SurfaceRules.sequence({string.Join(", ", parts)})";
        return $"SurfaceRules.ifTrue(SurfaceRules.isBiome({key}), {inner})";
    }
}
